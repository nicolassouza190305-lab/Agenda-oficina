// ============================================================
// seguranca.js - hash de senha (SHA-256 com salt), em JS puro
// Evita guardar a senha em texto no banco. Sem dependências extras.
// (Para um app de produção, o ideal é hash no servidor.)
// ============================================================

// Constantes do SHA-256 (raízes de primos), calculadas na carga do módulo
const PRIMOS = [];
for (let n = 2; PRIMOS.length < 64; n++) {
  if (PRIMOS.every((p) => n % p !== 0)) PRIMOS.push(n);
}
const fracao32 = (x) => Math.floor((x - Math.floor(x)) * 4294967296);
const K = PRIMOS.map((p) => fracao32(Math.cbrt(p)));
const H0 = PRIMOS.slice(0, 8).map((p) => fracao32(Math.sqrt(p)));

function utf8(str) {
  const out = [];
  for (let i = 0; i < str.length; i++) {
    let c = str.charCodeAt(i);
    if (c >= 0xd800 && c < 0xdc00 && i + 1 < str.length) {
      const d = str.charCodeAt(i + 1);
      if (d >= 0xdc00 && d < 0xe000) {
        c = 0x10000 + ((c - 0xd800) << 10) + (d - 0xdc00);
        i++;
      }
    }
    if (c < 0x80) out.push(c);
    else if (c < 0x800) out.push(0xc0 | (c >> 6), 0x80 | (c & 63));
    else if (c < 0x10000)
      out.push(0xe0 | (c >> 12), 0x80 | ((c >> 6) & 63), 0x80 | (c & 63));
    else
      out.push(
        0xf0 | (c >> 18),
        0x80 | ((c >> 12) & 63),
        0x80 | ((c >> 6) & 63),
        0x80 | (c & 63)
      );
  }
  return out;
}

const rotr = (x, n) => (x >>> n) | (x << (32 - n));

export function sha256(texto) {
  const bytes = utf8(texto);
  const bits = bytes.length * 8;
  bytes.push(0x80);
  while (bytes.length % 64 !== 56) bytes.push(0);
  const hi = Math.floor(bits / 4294967296);
  const lo = bits >>> 0;
  bytes.push(
    (hi >>> 24) & 255, (hi >>> 16) & 255, (hi >>> 8) & 255, hi & 255,
    (lo >>> 24) & 255, (lo >>> 16) & 255, (lo >>> 8) & 255, lo & 255
  );

  const h = H0.slice();
  const w = new Array(64);
  for (let i = 0; i < bytes.length; i += 64) {
    for (let t = 0; t < 16; t++) {
      w[t] =
        (bytes[i + 4 * t] << 24) |
        (bytes[i + 4 * t + 1] << 16) |
        (bytes[i + 4 * t + 2] << 8) |
        bytes[i + 4 * t + 3];
    }
    for (let t = 16; t < 64; t++) {
      const s0 = rotr(w[t - 15], 7) ^ rotr(w[t - 15], 18) ^ (w[t - 15] >>> 3);
      const s1 = rotr(w[t - 2], 17) ^ rotr(w[t - 2], 19) ^ (w[t - 2] >>> 10);
      w[t] = (w[t - 16] + s0 + w[t - 7] + s1) | 0;
    }
    let [a, b, c, d, e, f, g, hh] = h;
    for (let t = 0; t < 64; t++) {
      const S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const ch = (e & f) ^ (~e & g);
      const t1 = (hh + S1 + ch + K[t] + w[t]) | 0;
      const S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const mj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + mj) | 0;
      hh = g; g = f; f = e; e = (d + t1) | 0;
      d = c; c = b; b = a; a = (t1 + t2) | 0;
    }
    h[0] = (h[0] + a) | 0; h[1] = (h[1] + b) | 0;
    h[2] = (h[2] + c) | 0; h[3] = (h[3] + d) | 0;
    h[4] = (h[4] + e) | 0; h[5] = (h[5] + f) | 0;
    h[6] = (h[6] + g) | 0; h[7] = (h[7] + hh) | 0;
  }
  return h.map((x) => (x >>> 0).toString(16).padStart(8, "0")).join("");
}

export function gerarSalt() {
  let s = "";
  for (let i = 0; i < 32; i++) s += Math.floor(Math.random() * 16).toString(16);
  return s;
}

// Hash da senha: SHA-256 repetido 1000x misturando o salt
export function hashSenha(senha, salt) {
  let h = sha256(`${salt}:${senha}`);
  for (let i = 0; i < 1000; i++) h = sha256(`${h}:${salt}`);
  return h;
}
